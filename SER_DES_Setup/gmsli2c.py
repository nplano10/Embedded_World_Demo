def readCpp(file) -> list:
    """
    Converts .cpp script generated by the GMSL CSI tool to a list of writes
    (also lists) that contains only the device address, register address
    and value to be written. 
    """
    writes = []
    try:
        with open(file, 'r') as f:
            for line_number, line in enumerate(f, start=1):
                if line.startswith('0x04'):
                    line = line.replace(' ', '')
                    uncomment = line.split('//')
                    bytes = uncomment[0].split(',')
                    writes.append(bytes2write(bytes[1 : -1]))
                if line.startswith('0x00'):
                    # Handle lines starting with '0x00' if needed
                    pass
    except FileNotFoundError:
        logger.error(f"The file {file} was not found.")
    except Exception as e:
        logger.error(f"An error occurred at line {line_number}: {e}")
    return writes

