def bytes2write(bytes) -> list:
    """
    Reformat [DEV, MSB, LSB, VAL]
    to [DEV, REG_16bit, VAL]
    """
    try:
        dev = int(bytes[0], 0)
        msb = int(bytes[1], 0)
        lsb = int(bytes[2], 0)
        val = int(bytes[3], 0)
        return [dev, msb * 256 + lsb, val]
    except (IndexError, ValueError) as e:
        logger.error(f"Error processing bytes: {bytes} - {e}")
        return []

class GMSLi2c:
    def __init__(self, host):
        try:
            self.host = host
            self.DEBUG = False
            self.LOG = False
        except Exception as e:
            logger.error(f"Error initializing GMSLi2c: {e}")
    
    def regRead(self, dev, reg):
        return self.host.regRead(dev, reg)
    
    def regWrite(self, dev, reg, val, mask = 0xff):
        if mask != 0xff:
            rdVal = self.regRead(dev, reg)
            val = (val and mask) or (~mask and rdVal)
        
        self.host.regWrite(dev, reg, val)

        if self.LOG:
            logger.info(f'Writing: dev = {hex(dev)}, reg = {hex(reg)}, val = {hex(val)}')
        if self.DEBUG:
            time.sleep(0.1)
            logger.debug(f'Debug readbck: dev = {hex(dev)}, reg = {hex(reg)}, val = {hex(self.regRead(dev, reg))}')

    def parseFile(self, file):
        logger.info(f"Parsing file: {file}")
        if file.endswith('cpp'):
            seq = readCpp(file)[::-1]
            logger.info(f"Sequence loaded: {seq}")
        
        while seq:
            dev, reg, val = seq.pop()
            logger.info(f"Processing: dev = {hex(dev)}, reg = {hex(reg)}, val = {hex(val)}")

            if dev == 0:
                time.sleep(10e-2)
            else:
                self.regWrite(dev, reg, val)
                logger.info(f"Written: dev = {hex(dev)}, reg = {hex(reg)}, val = {hex(val)}")



